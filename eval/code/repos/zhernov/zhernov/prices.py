"""Цены изделий и скидки для магазинов."""

from dataclasses import dataclass

# Скидка магазину в зависимости от числа изделий в заказе: (от скольких штук, скидка).
СКИДКИ = [
    (500, 0.10),
    (200, 0.05),
]


@dataclass(frozen=True)
class Цена:
    изделие: str
    рубли: int
    копейки: int

    def в_копейках(self) -> int:
        return self.рубли * 100 + self.копейки


def discount(quantity: int) -> float:
    """Скидка магазину за объём заказа: пять процентов от двухсот штук, десять от пятисот."""
    for порог, скидка in СКИДКИ:
        if quantity >= порог:
            return скидка
    return 0.0


def order_price_kopecks(цены: dict[str, Цена], заказ: dict[str, int]) -> int:
    """Сумма заказа в копейках со скидкой за общий объём; копейки округляются вниз."""
    всего = sum(цены[изделие].в_копейках() * штук for изделие, штук in заказ.items())
    скидка = discount(sum(заказ.values()))
    return int(всего * (1 - скидка))
